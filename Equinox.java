public class Equinox
{

    public static void main (String[] args)
    {
        int sunShine = 12; // Hours Of Day time
        int moonShine = 12; // Hours Of Night time

        if(sunShine == moonShine){
            System.out.println("We Have Ourselves an Equinox!!! ");
        }else{
            System.out.println("No Equinox Today :(");
        }
    }
    
}